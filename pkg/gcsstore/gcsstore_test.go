const mockID = "123456789abcdefghijklmnopqrstuvwxyz"
const mockBucket = "bucket"
const mockSize = 1337
const mockReaderData = "helloworld"

var mockTusdInfoJson = fmt.Sprintf(`{"ID":"%s","Size":%d,"MetaData":{"foo":"bar"},"Storage":{"Bucket":"bucket","Key":"%s","Type":"gcsstore"}}`, mockID, mockSize, mockID)
var mockTusdInfo = handler.FileInfo{
	ID:   mockID,
	Size: mockSize,
	MetaData: map[string]string{
		"foo": "bar",
	},
	Storage: map[string]string{
		"Type":   "gcsstore",
		"Bucket": mockBucket,
		"Key":    mockID,
	},
}

var mockPartial0 = fmt.Sprintf("%s_0", mockID)
var mockPartial1 = fmt.Sprintf("%s_1", mockID)
var mockPartial2 = fmt.Sprintf("%s_2", mockID)
var mockPartials = []string{mockPartial0, mockPartial1, mockPartial2}

func TestNewUpload(t *testing.T) {
	mockCtrl := gomock.NewController(t)
	defer mockCtrl.Finish()
	assert := assert.New(t)

	service := NewMockGCSAPI(mockCtrl)
	store := gcsstore.New(mockBucket, service)

	assert.Equal(store.Bucket, mockBucket)

	data, err := json.Marshal(mockTusdInfo)
	assert.Nil(err)

	r := bytes.NewReader(data)

	params := gcsstore.GCSObjectParams{
		Bucket: store.Bucket,
		ID:     fmt.Sprintf("%s.info", mockID),
	}

	ctx := context.Background()
	service.EXPECT().WriteObject(ctx, params, r).Return(int64(r.Len()), nil)

	upload, err := store.NewUpload(context.Background(), mockTusdInfo)
	assert.Nil(err)
	assert.NotNil(upload)
}

func TestNewUploadRejectsCollidingIDs(t *testing.T) {
	for _, id := range []string{
		// Data would be written into the info object of upload "other".
		"other.info",
		"dir/other.info",
		// Data would be written into a chunk of upload "other".
		"other_0",
		"other_12",
		"dir/other_3",
		// Data would be written into a temporary object of upload "other".
		"other_tmp_0_1",
		"other_tmp_10_20",
	} {
		t.Run(id, func(t *testing.T) {
			mockCtrl := gomock.NewController(t)
			defer mockCtrl.Finish()

			// No calls are expected on the service, so gomock fails the test
			// if any object is written.
			service := NewMockGCSAPI(mockCtrl)
			store := gcsstore.New(mockBucket, service)

			upload, err := store.NewUpload(context.Background(), handler.FileInfo{ID: id, Size: mockSize})
			assert.Nil(t, upload)
			var handlerErr handler.Error
			assert.True(t, errors.As(err, &handlerErr))
			assert.Equal(t, "ERR_INVALID_UPLOAD_ID", handlerErr.ErrorCode)
		})
	}
}

func TestNewUploadAcceptsRegularIDs(t *testing.T) {
	for _, id := range []string{
		"", // Generated by uid.Uid()
		mockID,
		"photo.jpg",
		"dir/photo.info.jpg",
		"other.Info", // Object names are case-sensitive.
		"other_",
		"other_tmp",
		"other_1a",
		"other_1/file",
		"2024_report",
		"12345",
	} {
		t.Run(id, func(t *testing.T) {
			mockCtrl := gomock.NewController(t)
			defer mockCtrl.Finish()
			ctx := context.Background()

			service := NewMockGCSAPI(mockCtrl)
			store := gcsstore.New(mockBucket, service)

			expectedParams := gomock.Any()
			if id != "" {
				expectedParams = gomock.Eq(gcsstore.GCSObjectParams{
					Bucket: mockBucket,
					ID:     id + ".info",
				})
			}
			service.EXPECT().WriteObject(ctx, expectedParams, gomock.Any()).Return(int64(1), nil)

			upload, err := store.NewUpload(ctx, handler.FileInfo{ID: id, Size: mockSize})
			assert.Nil(t, err)
			assert.NotNil(t, upload)
		})
	}
}

